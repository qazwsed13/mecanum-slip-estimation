# -*- coding: utf-8 -*-
"""
make_tables.py — 从 npz 结果一键生成论文 LaTeX 表格（防手抄误差）
====================================================================
输出：manuscript/tables_v0.1.tex（Table 1 主对比 + Table 2 消融）
      控制台同步打印数值便于核对。
运行：python make_tables.py
"""

from pathlib import Path

import numpy as np

DATA = Path(__file__).resolve().parent.parent / "data"
OUT = Path(__file__).resolve().parent.parent / "manuscript" / "tables_v0.1.tex"


def g(d, key, fmt="%.4f"):
    if key not in d.files:
        return "TBD"
    return fmt % float(d[key])


def main():
    b = np.load(DATA / "baseline_results_v1.npz")
    s = np.load(DATA / "supervised_results_v1.npz")
    m = np.load(DATA / "main_method_results_v1.npz")
    try:
        ab = np.load(DATA / "ablation_results_v1.npz")
    except FileNotFoundError:
        ab = None
    try:
        im = np.load(DATA / "table2_init_matched_v1.npz")   # Q1 修正：匹配锚点补跑
    except FileNotFoundError:
        im = None

    rows1 = [
        ("Wheel odometry (no slip)", "--", "0",
         g(b, "test_B1_wheel_slip_mae_event"), g(b, "test_B1_wheel_slip_mae_all"),
         g(b, "test_B1_wheel_drift_pct", "%.2f"), g(b, "loco_B1_wheel_slip_mae_event")),
        ("Wheel + gyro odometry", "--", "0",
         g(b, "test_B1_wheel_gyro_slip_mae_event"), g(b, "test_B1_wheel_gyro_slip_mae_all"),
         g(b, "test_B1_wheel_gyro_drift_pct", "%.2f"),
         g(b, "loco_B1_wheel_gyro_slip_mae_event")),
        ("UMBmark-style calibration", "--", "0",
         g(b, "test_B2_umbmark_slip_mae_event"), g(b, "test_B2_umbmark_slip_mae_all"),
         g(b, "test_B2_umbmark_drift_pct", "%.2f"),
         g(b, "loco_B2_umbmark_slip_mae_event")),
        ("Adaptive EKF", "--", "0",
         g(b, "test_B3_ekf_slip_mae_event"), g(b, "test_B3_ekf_slip_mae_all"),
         g(b, "test_B3_ekf_drift_pct", "%.2f"), g(b, "loco_B3_ekf_slip_mae_event")),
        ("Supervised BiLSTM", f"{int(s['lstm_nparams']):,}", "100\\%",
         g(s, "lstm_test_slip_mae_event"), g(s, "lstm_test_slip_mae_all"),
         g(s, "lstm_test_drift_pct", "%.2f"), g(s, "lstm_loco_slip_mae_event")),
        ("Supervised GRU", f"{int(s['gru_nparams']):,}", "100\\%",
         g(s, "gru_test_slip_mae_event"), g(s, "gru_test_slip_mae_all"),
         g(s, "gru_test_drift_pct", "%.2f"), g(s, "gru_loco_slip_mae_event")),
        ("Supervised 1D-CNN", f"{int(s['cnn_nparams']):,}", "100\\%",
         g(s, "cnn_test_slip_mae_event"), g(s, "cnn_test_slip_mae_all"),
         g(s, "cnn_test_drift_pct", "%.2f"), g(s, "cnn_loco_slip_mae_event")),
        ("Supervised attention", f"{int(s['attn_nparams']):,}", "100\\%",
         g(s, "attn_test_slip_mae_event"), g(s, "attn_test_slip_mae_all"),
         g(s, "attn_test_drift_pct", "%.2f"), g(s, "attn_loco_slip_mae_event")),
        ("Ours (network only)", f"{int(m['test_net_only_nparams']):,}" if "test_net_only_nparams" in m.files else "71,812", "5\\%",
         g(m, "test_net_only_slip_mae_event"), g(m, "test_net_only_slip_mae_all"),
         g(m, "test_net_only_drift_pct", "%.2f"), g(m, "loco_net_only_slip_mae_event")),
        ("\\textbf{Ours (refined)}", "71,812", "5\\%",
         "\\textbf{%s}" % g(m, "test_refined_slip_mae_event"),
         g(m, "test_refined_slip_mae_all"),
         g(m, "test_refined_drift_pct", "%.2f"),
         "\\textbf{%s}" % g(m, "loco_refined_slip_mae_event")),
    ]

    tex = [
        "% Table 1: main comparison (generated by make_tables.py — do not edit by hand)",
        "\\begin{tabular}{lrrrrrr}", "\\toprule",
        "Method & Params & Labels & evMAE (test) & allMAE (test) & drift (\\%) & evMAE (LOCO) \\\\",
        "\\midrule",
    ]
    for name, par, lab, ev, al, dr, evl in rows1:
        tex.append(f"{name} & {par} & {lab} & {ev} & {al} & {dr} & {evl} \\\\")
    tex += ["\\bottomrule", "\\end{tabular}", ""]

    # Table 2: ablations
    tex += ["% Table 2: ablations (from ablation_results_v1.npz)",
            "\\begin{tabular}{llrrr}", "\\toprule",
            "Study & Setting & evMAE & allMAE & drift (\\%) \\\\", "\\midrule"]
    if ab is not None:
        def row(tag, label):
            return (f"{label} & {g(ab, tag + '__slip_mae_event')} & "
                    f"{g(ab, tag + '__slip_mae_all')} & "
                    f"{g(ab, tag + '__drift_pct', '%.2f')} \\\\")
        for f in (0.0, 0.01, 0.05, 0.20):
            tex.append(row(f"A_label_curve f={f:.2f}", f"Labels = {int(f*100)}\\%"))
        tex.append("\\midrule")

        def row_src(tag, label, src):
            return (f"{label} & {g(src, tag + '_slip_mae_event')} & "
                    f"{g(src, tag + '_slip_mae_all')} & "
                    f"{g(src, tag + '_drift_pct', '%.2f')} \\\\")

        tex.append(row_src("random_matched_test", "Init = random (matched anchors)",
                           im if im is not None else ab))
        tex.append(row("A_label_curve f=0.05", "Init = encoder (5\\%)"))
        tex.append(row("B_init sup100(ref)", "Init = encoder (100\\%, ref.)"))
        tex.append("\\midrule")
        tex.append(row("C_wlab 10", "$w_{lab}$ = 10"))
        tex.append(row("A_label_curve f=0.05", "$w_{lab}$ = 50"))
        tex.append(row("C_wlab 200", "$w_{lab}$ = 200"))
        tex.append(row("C_lampr 0.0", "$\\lambda_{pr}$ = 0"))
        tex.append(row("A_label_curve f=0.05", "$\\lambda_{pr}$ = 1"))
        tex.append(row("C_lampr 5.0", "$\\lambda_{pr}$ = 5"))
        tex.append(row("C_lamsm 0.3", "$\\lambda_{sm}$ = 0.3"))
        tex.append(row("C_lamsm 3.0", "$\\lambda_{sm}$ = 3.0"))
        tex.append("\\midrule")
        tex.append(row("A_label_curve f=0.05", "Noise $\\times$1"))
        tex.append(row("D_noise x2", "Noise $\\times$2"))
        tex.append(row("D_noise x3", "Noise $\\times$3"))
    else:
        tex.append("Ablations & pending & TBD & TBD & TBD \\\\")
    tex += ["\\bottomrule", "\\end{tabular}", ""]

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(tex), encoding="utf-8")
    print("\n".join(tex))
    print(f"\nsaved -> {OUT}")


if __name__ == "__main__":
    main()
